#!/usr/bin/env python3
"""Prints CREDITS.txt for Dhow.app and the DMG: Dhow's license, UniFFI's
(MPL-2.0, whose source the DMG must point to: ARCHITECTURE §9), and every
Rust crate linked into the app (dhow-ffi's normal dependencies on macOS),
from `cargo metadata`. Usage: credits.py <core dir>"""

import json
import subprocess
import sys

core = sys.argv[1]
meta = json.loads(
    subprocess.run(
        ["cargo", "metadata", "--format-version", "1", "--locked",
         "--filter-platform", "aarch64-apple-darwin"],
        cwd=core, check=True, capture_output=True, text=True).stdout)

packages = {p["id"]: p for p in meta["packages"]}
nodes = {n["id"]: n for n in meta["resolve"]["nodes"]}
root = next(p["id"] for p in meta["packages"] if p["name"] == "dhow-ffi")

# What links into the library: normal dependencies, not dev or build ones.
linked, todo = set(), [root]
while todo:
    node = nodes[todo.pop()]
    for dep in node["deps"]:
        if any(k["kind"] is None for k in dep["dep_kinds"]) and dep["pkg"] not in linked:
            linked.add(dep["pkg"])
            todo.append(dep["pkg"])

own = {"dhow-core", "dhow-ffi"}
crates = sorted(
    (packages[i] for i in linked if packages[i]["name"] not in own),
    key=lambda p: (p["name"], p["version"]))

print("""Dhow
Copyright the Dhow contributors. Free software under the GNU General Public
License, version 3 or (at your option) any later version: see LICENSE.
Source code: https://github.com/m3di/dhow

Dhow includes code generated by and linked from UniFFI (Mozilla), under the
Mozilla Public License 2.0. Its source code: https://github.com/mozilla/uniffi-rs
The MPL-2.0 text: https://www.mozilla.org/MPL/2.0/

Dhow's engine links these Rust crates, each under the license shown; their
sources and license texts are on https://crates.io and at the repository
given.
""")
for p in crates:
    where = p.get("repository") or f"https://crates.io/crates/{p['name']}"
    print(f"{p['name']} {p['version']}: {p.get('license') or 'see its source'} ({where})")
